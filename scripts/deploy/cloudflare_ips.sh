#!/usr/bin/env bash
# Cloudflare IP ranges (https://www.cloudflare.com/ips/) for two tasks: the real client address in nginx and port 80/443 of the server closed
# to everyone else, so that the origin cannot be reached bypassing Cloudflare.
#   cloudflare_ips.sh nginx   - writes deploy/cloudflare_real_ip.inc (set_real_ip_from + CF-Connecting-IP); then
#                               `docker compose ... restart web`;
#   cloudflare_ips.sh ufw     - allows 80/443 only to these ranges (needs ufw and root); closed to everyone else;
#   cloudflare_ips.sh print   - just the list.
# The Cloudflare list changes rarely: run it once a month (cron) and after Cloudflare announcements. It stores nothing and
# uses no tokens - it reads the public lists.
set -euo pipefail

MODE="${1:-print}"
OUT="${CLOUDFLARE_REAL_IP_FILE:-$(dirname "$0")/../../deploy/cloudflare_real_ip.inc}"
CIDR='^[0-9a-fA-F:.]+/[0-9]{1,3}$'

fetch() {
    local list
    list="$(curl -fsS --max-time 20 "https://www.cloudflare.com/$1")"
    [ -n "$list" ] || { echo "empty list $1" >&2; exit 1; }
    # A foreign response must not get into the nginx config or firewall rules: only lines of the form address/length.
    while IFS= read -r line; do
        [[ "$line" =~ $CIDR ]] || { echo "unexpected line in $1: $line" >&2; exit 1; }
    done <<< "$list"
    printf '%s\n' "$list"
}

RANGES="$(fetch ips-v4; fetch ips-v6)"

case "$MODE" in
    print)
        printf '%s\n' "$RANGES" ;;
    nginx)
        mkdir -p "$(dirname "$OUT")"
        {
            echo "# Generated by scripts/deploy/cloudflare_ips.sh $(date -u +%F): Cloudflare addresses; the client is taken from CF-Connecting-IP."
            while IFS= read -r cidr; do echo "set_real_ip_from $cidr;"; done <<< "$RANGES"
            echo "real_ip_header CF-Connecting-IP;"
        } > "$OUT"
        echo "written $OUT" ;;
    ufw)
        while IFS= read -r cidr; do
            ufw allow proto tcp from "$cidr" to any port 80,443 comment 'cloudflare'
        done <<< "$RANGES"
        echo "Rules added. To close 80/443 to everyone else: ufw default deny incoming (allow SSH separately: ufw allow OpenSSH)." ;;
    *)
        echo "usage: $0 nginx|ufw|print" >&2; exit 2 ;;
esac
